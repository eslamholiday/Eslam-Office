"""Build grouped display captions; semantic keys and user reference names stay separate."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
groups = {
    'الرئيسية والتنقل': ['main.dart'],
    'الإدخال والعمليات': ['input_schema.dart', 'forms.dart', 'domain.dart'],
    'الحسابات والحركات': ['pages.dart', 'money_pages.dart'],
    'الكشوف والتصدير': ['statement_details.dart', 'reports.dart'],
    'الإعدادات والتخصيص': ['settings.dart', 'input_settings.dart', 'experience_settings.dart', 'label_settings.dart', 'config_transfer.dart', 'geography_settings.dart'],
    'الأزرار والخيارات': ['ui.dart', 'date_range_field.dart', 'experience.dart', 'clearance.dart'],
}
seen = set()
result = {}
for group, files in groups.items():
    values = set()
    for file in files:
        for match in re.finditer(r"'([^'\\\n]*(?:\\.[^'\\\n]*)*)'", (root / 'lib' / file).read_text()):
            text = match.group(1)
            if (re.search('[\u0600-\u06ff]', text) and '$' not in text
                    and '\\n' not in text and 1 < len(text) <= 45
                    and text not in seen):
                values.add(text)
    result[group] = sorted(values)
    seen.update(values)
lines = ['// Generated by tool/generate-label-catalog.py. Display captions, never IDs.',
         'const uiLabelGroups = <String, List<String>>{']
for group, values in result.items():
    lines.append('  ' + json.dumps(group, ensure_ascii=False) + ': [')
    lines.extend('    ' + json.dumps(v, ensure_ascii=False) + ',' for v in values)
    lines.append('  ],')
lines.append('};')
lines.append('final uiLabelCatalog = uiLabelGroups.values.expand((group) => group).toSet().toList()..sort();')
(root / 'lib' / 'label_catalog.dart').write_text('\n'.join(lines) + '\n')
print('Grouped captions:', {k: len(v) for k, v in result.items()})
